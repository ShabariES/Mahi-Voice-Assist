import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import { createHash } from 'node:crypto'

function makeServiceWorker(base, assets, version) {
  const precache = [
    base,
    `${base}manifest.webmanifest`,
    `${base}mahi-logo.svg`,
    `${base}favicon.svg`,
    `${base}mahi-pwa-192.png`,
    `${base}mahi-pwa-512.png`,
    `${base}mahi-maskable-512.png`,
    ...assets.map((asset) => `${base}${asset}`),
  ]
  const basePath = new URL(base, 'https://mahi.invalid').pathname

  return `/* Generated by Vite for Mahi Voice Assist. */
const CACHE_NAME = ${JSON.stringify(`mahi-app-shell-${version}`)};
const BASE_PATH = ${JSON.stringify(basePath)};
const PRECACHE_URLS = ${JSON.stringify(precache)};
const PRECACHE_PATHS = new Set(PRECACHE_URLS.map((path) => new URL(path, self.location.origin).pathname));
const APP_SHELL_URL = new URL(${JSON.stringify(base)}, self.location.origin).href;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(PRECACHE_URLS);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith('mahi-app-shell-') && key !== CACHE_NAME).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE_PATH)) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        return await fetch(request);
      } catch {
        return (await caches.match(APP_SHELL_URL)) || Response.error();
      }
    })());
    return;
  }

  const isAppAsset = PRECACHE_PATHS.has(url.pathname) || url.pathname.startsWith(new URL('assets/', self.location.origin + BASE_PATH).pathname);
  if (!isAppAsset) return;
  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') {
      const cache = await caches.open(CACHE_NAME);
      await cache.put(request, response.clone());
    }
    return response;
  })());
});
`
}

function pwaServiceWorkerPlugin(base) {
  return {
    name: 'mahi-pwa-service-worker',
    generateBundle(_options, bundle) {
      const assets = Object.values(bundle)
        .filter((entry) => entry.type === 'chunk' || (entry.type === 'asset' && String(entry.fileName).endsWith('.css')))
        .map((entry) => entry.fileName)
        .sort()
      const version = createHash('sha256').update(assets.join('|')).digest('hex').slice(0, 10)
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: makeServiceWorker(base, assets, version),
      })
    },
  }
}

const base = process.env.GITHUB_ACTIONS === 'true' ? '/Mahi-Voice-Assist/' : '/'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), pwaServiceWorkerPlugin(base)],
  // GitHub Pages hosts this repository under /Mahi-Voice-Assist/; local and
  // Render builds continue to use the domain root.
  base,
})
